/**
 * Generates supabase/seed.sql from src/data/mockData.js.
 *
 *   node scripts/generate-seed.mjs
 *
 * The data itself (id merging, draft cards, ...) is built in scripts/seed-data.mjs.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { RUTAS_MOCK, DATOS_CURIOSOS_MOCK } from '../src/data/mockData.js'
import { RANKS, canon, minutes, sites, stops, cards, draftCards } from './seed-data.mjs'

// --- SQL literal helpers ----------------------------------------------------
const str = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const num = (v) => (v == null || Number.isNaN(v) ? 'null' : String(v))
// Re-seeding must not undo images uploaded to Supabase Storage (scripts/upload-images.mjs).
const keepUploadedImage = (table) =>
  `image_url = case when public.${table}.image_url like '%/storage/v1/object/public/site-images/%' then public.${table}.image_url else excluded.image_url end`
const rows = (list) => list.map((r) => `  (${r.join(', ')})`).join(',\n')

// --- Emit --------------------------------------------------------------------
const out = []
out.push('-- GENERATED by scripts/generate-seed.mjs from src/data/mockData.js. Do not edit by hand.')
out.push('-- Re-runnable: content is upserted; player data (user_cards, scans, qr_codes) is never touched.')
out.push('')

out.push('insert into public.ranks (name, min_points) values')
out.push(
  rows(RANKS.map(([n, p]) => [str(n), p])) +
    '\non conflict (name) do update set min_points = excluded.min_points;'
)
out.push('')

out.push('insert into public.sites (id, name, category, address, description, hours, lat, lng, points, rarity, icon, image_url, kind, map_top_pct, map_left_pct) values')
out.push(
  rows(
    [...sites.values()].map((s) => [
      str(s.id), str(s.name), str(s.category), str(s.address), str(s.description),
      str(s.hours), num(s.lat), num(s.lng), num(s.points), `${str(s.rarity)}::public.rarity`,
      str(s.icon), str(s.image), str(s.kind), num(s.top), num(s.left)
    ])
  )
)
out.push(`on conflict (id) do update set
  name = excluded.name, category = excluded.category, address = excluded.address,
  description = excluded.description, hours = excluded.hours, lat = excluded.lat,
  lng = excluded.lng, points = excluded.points, rarity = excluded.rarity,
  icon = excluded.icon, ${keepUploadedImage('sites')}, kind = excluded.kind,
  map_top_pct = excluded.map_top_pct, map_left_pct = excluded.map_left_pct;`)
out.push('')

out.push('insert into public.routes (id, title, description, category, distance_km, est_minutes, difficulty, icon, image_url, badge_text, badge_type) values')
out.push(
  rows(
    RUTAS_MOCK.map((r) => [
      str(r.id), str(r.titulo), str(r.descripcion), str(r.categoria),
      num(parseFloat(r.distancia)), num(minutes(r.tiempoEstimado)), str(r.dificultad),
      str(r.icono), str(r.imagen), str(r.badgeTexto), str(r.badgeTipo)
    ])
  ) +
    `
on conflict (id) do update set
  title = excluded.title, description = excluded.description, category = excluded.category,
  distance_km = excluded.distance_km, est_minutes = excluded.est_minutes,
  difficulty = excluded.difficulty, icon = excluded.icon, ${keepUploadedImage('routes')},
  badge_text = excluded.badge_text, badge_type = excluded.badge_type;`
)
out.push('')

out.push('delete from public.route_stops;')
out.push('insert into public.route_stops (route_id, site_id, position, subtitle, detail) values')
out.push(
  rows(
    RUTAS_MOCK.flatMap((r) =>
      r.museos.map((s, i) => [str(r.id), str(canon(s.id)), i + 1, str(s.subtitulo), str(s.detalle)])
    )
  ) + ';'
)
out.push('')

out.push('insert into public.cards (id, site_id, title, category, category_label, rarity, hint, hint_icon, short_history, image_url) values')
out.push(
  rows(
    cards.map((c) => [
      str(c.siteId), str(c.siteId), str(c.titulo), str(c.categoria), str(c.categoriaLabel),
      `${str(c.rareza)}::public.rarity`, str(c.pista), str(c.iconoPista),
      str(c.historiaCorta), str(c.imagen)
    ])
  ) +
    `
on conflict (id) do update set
  site_id = excluded.site_id, title = excluded.title, category = excluded.category,
  category_label = excluded.category_label, rarity = excluded.rarity, hint = excluded.hint,
  hint_icon = excluded.hint_icon, short_history = excluded.short_history,
  is_draft = false, ${keepUploadedImage('cards')};`
)
out.push('')

out.push('')
out.push('-- Draft cards (auto-generated placeholders; is_draft = true). Never overwritten by re-seeding.')
out.push('insert into public.cards (id, site_id, title, category, category_label, rarity, hint, hint_icon, short_history, image_url, is_draft) values')
out.push(
  rows(
    draftCards.map((c) => [
      str(c.id), str(c.id), str(c.titulo), str(c.categoria), str(c.categoriaLabel),
      `${str(c.rareza)}::public.rarity`, str(c.pista), str(c.iconoPista),
      str(c.historiaCorta), 'null', 'true'
    ])
  ) + '\non conflict (id) do nothing;'
)
out.push('')

out.push('insert into public.fun_facts (id, position, badge, icon, text_prefix, text_highlight, text_suffix, location, gradient) values')
out.push(
  rows(
    DATOS_CURIOSOS_MOCK.map((d, i) => [
      str(d.id), i + 1, str(d.badge), str(d.icono), str(d.textoPrefix),
      str(d.textoDestacado), str(d.textoSuffix), str(d.ubicacion), str(d.gradiente)
    ])
  ) +
    `
on conflict (id) do update set
  position = excluded.position, badge = excluded.badge, icon = excluded.icon,
  text_prefix = excluded.text_prefix, text_highlight = excluded.text_highlight,
  text_suffix = excluded.text_suffix, location = excluded.location, gradient = excluded.gradient;`
)
out.push('')

const target = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url))
writeFileSync(target, out.join('\n'))
console.log(
  `seed.sql: ${sites.size} sites, ${RUTAS_MOCK.length} routes, ${stops.length} stops, ${cards.length} authored + ${draftCards.length} draft cards, ${DATOS_CURIOSOS_MOCK.length} fun facts`
)
